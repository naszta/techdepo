//! `xtask seed`: D1 seed SQL for per-org inventory.
//!
//! Products are compiled into the workers, so D1 only holds per-org stock, and `Org/provision`
//! seeds it when an org first appears. This command produces the same rows for every org that
//! already exists, which is what a catalog change needs: new products get their
//! `default_stock`, and existing stock is left alone (`INSERT OR IGNORE`). Running it twice is
//! harmless.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::{SystemTime, UNIX_EPOCH};

use techdepo_catalog::{CATALOG_VERSION, Catalog};

/// Command-line options.
#[derive(Debug, Default)]
pub struct Options {
    /// Write the SQL here instead of stdout.
    pub out: Option<PathBuf>,
    /// Apply migrations and the SQL to the local D1 through wrangler.
    pub local: bool,
}

pub fn run(options: Options) -> Result<(), String> {
    let catalog = Catalog::load_embedded().map_err(|e| format!("catalog does not parse: {e}"))?;
    catalog.validate().map_err(|e| {
        format!(
            "{e}refusing to seed an invalid catalog (run `cargo run -p xtask -- catalog validate`)"
        )
    })?;
    let now_ms = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_err(|e| e.to_string())?
        .as_millis();
    let sql = inventory_sql(&catalog, now_ms);

    if options.local {
        let path = options
            .out
            .unwrap_or_else(|| workspace_root().join("target/seed-inventory.sql"));
        write(&path, &sql)?;
        apply_local(&path)
    } else if let Some(path) = options.out {
        write(&path, &sql)?;
        eprintln!("wrote {}", path.display());
        Ok(())
    } else {
        print!("{sql}");
        Ok(())
    }
}

/// One idempotent statement adding every product to every org's inventory at default stock.
pub fn inventory_sql(catalog: &Catalog, now_ms: u128) -> String {
    let mut sql = format!(
        "-- Generated by `cargo run -p xtask -- seed` from catalog {CATALOG_VERSION} ({} products).\n\
         -- Adds missing products to the inventory of every provisioned org at their default stock.\n\
         -- Existing stock is kept; `Org/reset_demo` resets it.\n\
         WITH seed (product_id, stock) AS (VALUES\n",
        catalog.len()
    );
    let rows: Vec<String> = catalog
        .all()
        .iter()
        .map(|p| format!("    ('{}', {})", sql_text(p.id.as_str()), p.default_stock))
        .collect();
    sql.push_str(&rows.join(",\n"));
    let _ = write!(
        sql,
        "\n)\nINSERT OR IGNORE INTO inventory (org_id, product_id, stock, updated_at)\n\
         SELECT orgs.id, seed.product_id, seed.stock, {now_ms} FROM orgs CROSS JOIN seed;\n"
    );
    sql
}

/// A string literal body with quotes doubled (product IDs are slugs, so this is belt and braces).
fn sql_text(s: &str) -> String {
    s.replace('\'', "''")
}

fn write(path: &Path, sql: &str) -> Result<(), String> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    }
    std::fs::write(path, sql).map_err(|e| format!("{}: {e}", path.display()))
}

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask lives in the workspace root")
        .to_path_buf()
}

/// `wrangler d1 migrations apply` and `wrangler d1 execute` against the shared local state
/// (`.wrangler/state`), from `apps/services` whose `wrangler.toml` binds the database.
fn apply_local(sql: &Path) -> Result<(), String> {
    let root = workspace_root();
    let state = root.join(".wrangler/state");
    let state = state.to_string_lossy();
    let sql = std::fs::canonicalize(sql).map_err(|e| format!("{}: {e}", sql.display()))?;
    let sql = sql.to_string_lossy();
    let steps: [&[&str]; 2] = [
        &[
            "d1",
            "migrations",
            "apply",
            "techdepo",
            "--local",
            "--persist-to",
            &state,
        ],
        &[
            "d1",
            "execute",
            "techdepo",
            "--local",
            "--persist-to",
            &state,
            "--file",
            &sql,
        ],
    ];
    for args in steps {
        eprintln!("$ wrangler {}", args.join(" "));
        let status = Command::new("wrangler")
            .args(args)
            .current_dir(root.join("apps/services"))
            // Non-interactive: wrangler skips its confirmation prompt in CI mode.
            .env("CI", "true")
            .status()
            .map_err(|e| format!("could not run wrangler: {e}"))?;
        if !status.success() {
            return Err(format!("wrangler {} failed ({status})", args.join(" ")));
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn covers_every_product() {
        let catalog = Catalog::global();
        let sql = inventory_sql(catalog, 1_700_000_000_000);
        for product in catalog.all() {
            assert!(
                sql.contains(&format!("('{}', {})", product.id, product.default_stock)),
                "{}",
                product.id
            );
        }
        assert!(sql.contains("INSERT OR IGNORE INTO inventory"));
        assert!(sql.trim_end().ends_with("CROSS JOIN seed;"));
    }
}
