/// Parses `KEY=value` lines (comments, blank lines and `export ` prefixes allowed; values may be
/// quoted).
pub fn parse(text: &str) -> BTreeMap<String, String> {
    text.lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .filter_map(|l| {
            let l = l.strip_prefix("export ").unwrap_or(l);
            let (key, value) = l.split_once('=')?;
            let value = value.trim();
            let value = value
                .strip_prefix('"')
                .and_then(|v| v.strip_suffix('"'))
                .or_else(|| value.strip_prefix('\'').and_then(|v| v.strip_suffix('\'')))
                .unwrap_or(value);
            Some((key.trim().to_owned(), value.to_owned()))
        })
        .collect()
}

/// `.dev.vars` content for `keys` (set, non-empty values only).
pub fn render(source: &str, values: &BTreeMap<String, String>, keys: &[&str]) -> String {
    let mut out =
        format!("# Generated by `cargo run -p xtask -- dev-vars` from {source}. Do not edit.\n");
    for key in keys {
        if let Some(value) = values.get(*key).filter(|v| !v.is_empty()) {
            let escaped = value.replace('\\', "\\\\").replace('"', "\\\"");
            out.push_str(&format!("{key}=\"{escaped}\"\n"));
        }
    }
    out
}

/// The repository root.
pub fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .map(Path::to_path_buf)
        .unwrap_or_else(|| PathBuf::from("."))
}

pub fn run() -> Result<(), String> {
    let root = root();
    let (source, text) = match std::fs::read_to_string(root.join(".env")) {
        Ok(text) => (".env", text),
        Err(_) => {
            eprintln!("no .env, using .env.example (copy it to .env to customise)");
            let text = std::fs::read_to_string(root.join(".env.example"))
                .map_err(|e| format!("reading .env.example: {e}"))?;
            (".env.example", text)
        }
    };
    let values = parse(&text);
    for (dir, keys) in WORKERS {
        let path = root.join(dir).join(".dev.vars");
        let content = render(source, &values, keys);
        std::fs::write(&path, &content).map_err(|e| format!("writing {}: {e}", path.display()))?;
        let count = content.lines().filter(|l| !l.starts_with('#')).count();
        println!("{dir}/.dev.vars: {count} keys");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_and_filters() {
        let values = parse("# c\nexport A=1\nB=\"two words\"\nC=\n D = 'x' \n");
        assert_eq!(values["A"], "1");
        assert_eq!(values["B"], "two words");
        assert_eq!(values["D"], "x");
        let out = render(".env", &values, &["B", "C", "Z"]);
        assert!(out.contains("B=\"two words\"\n"));
        assert!(!out.contains("C="), "empty values are left out");
    }
}
